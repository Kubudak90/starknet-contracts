export function getTokensByChainId(chainId: number): Token[] {
  return TOKENS_BY_CHAIN[chainId] || [];
}

export function findToken(chainId: number, addressOrSymbol: string): Token | undefined {
  const tokens = getTokensByChainId(chainId);
  const search = addressOrSymbol.toLowerCase();
  return tokens.find(
    (token) =>
      token.address.toLowerCase() === search || token.symbol.toLowerCase() === search
  );
}
